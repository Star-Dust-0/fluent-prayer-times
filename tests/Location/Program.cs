using System.Diagnostics;
using System.Net;
using System.Net.Http;
using FluentPrayerTimes;
var checks = 0;
void Check(bool ok, string label) { checks++; if (!ok) throw new Exception(label); Console.WriteLine("PASS " + label); }
var good = """{"success":true,"latitude":30.04,"longitude":31.23,"city":"Cairo","country":"Egypt","country_code":"EG"}""";
var other = """{"loc":"30.04,31.23","city":"Cairo","country":"EG"}""";
Check(LocationDetection.Parse(good,"ipwho") is { Cc: "EG", City: "Cairo" }, "primary JSON metadata");
Check(LocationDetection.Parse(other,"ipinfo") is { Cc: "EG" }, "secondary JSON metadata");
foreach (var body in new[] { "{}", "{\"success\":false}", "{\"success\":true,\"latitude\":91,\"longitude\":0}", "{\"success\":true,\"latitude\":30,\"longitude\":181}", "{\"success\":true,\"latitude\":\"bad\",\"longitude\":0}" }) Check(LocationDetection.Parse(body,"ipwho") == null, "reject invalid primary " + body);
Check(!LocationDetection.Valid(double.NaN,0) && !LocationDetection.Valid(0,double.PositiveInfinity), "reject nonfinite");
Check(LocationDetection.Valid(0,0), "equator/Greenwich valid");
var calls = 0;
var handler = new Fake(async (uri,ct) => { calls++; await Task.Yield(); return new HttpResponseMessage(HttpStatusCode.OK) { Content=new StringContent(good) }; });
using var http = new HttpClient(handler);
var nativeFix = new LocationDetection.Fix(51,-0.1);
var fix = await LocationDetection.DetectAsync(_ => Task.FromResult<LocationDetection.Fix?>(nativeFix), http, (_,_)=>{});
Check(fix == nativeFix && calls == 0,"native wins without IP request");
fix = await LocationDetection.DetectAsync(_ => throw new UnauthorizedAccessException(),http,(_,_)=>{});
Check(fix?.Cc == "EG" && calls == 1,"permission denied falls back");
var sw = Stopwatch.StartNew();
fix = await LocationDetection.DetectAsync(_ => new TaskCompletionSource<LocationDetection.Fix?>().Task,http,(_,_)=>{},TimeSpan.FromMilliseconds(80));
Check(fix?.Cc == "EG" && sw.Elapsed < TimeSpan.FromSeconds(2),"noncooperative native timeout cannot hang");
using var secondary = new HttpClient(new Fake((uri,ct) => Task.FromResult(new HttpResponseMessage(uri.Contains("ipwho") ? HttpStatusCode.TooManyRequests : HttpStatusCode.OK) {Content=new StringContent(other)})));
fix = await LocationDetection.DetectAsync(_=>Task.FromResult<LocationDetection.Fix?>(null),secondary,(_,_)=>{});
Check(fix?.Cc == "EG","rate-limited primary falls back to secondary");
using var malformed = new HttpClient(new Fake((uri,ct) => Task.FromResult(new HttpResponseMessage(HttpStatusCode.OK) {Content=new StringContent(uri.Contains("ipwho")?"not json":other)})));
fix = await LocationDetection.DetectAsync(_=>Task.FromResult<LocationDetection.Fix?>(null),malformed,(_,_)=>{});
Check(fix?.Cc == "EG","malformed primary falls back");
using var offline = new HttpClient(new Fake((uri,ct) => throw new HttpRequestException()));
fix = await LocationDetection.DetectAsync(_=>Task.FromResult<LocationDetection.Fix?>(null),offline,(_,_)=>{});
Check(fix == null,"offline fails safely without inventing location");
using var hangs = new HttpClient(new Fake((uri,ct)=>new TaskCompletionSource<HttpResponseMessage>().Task));
sw.Restart();
fix = await LocationDetection.DetectAsync(_=>Task.FromResult<LocationDetection.Fix?>(null),hangs,(_,_)=>{},httpTimeout:TimeSpan.FromMilliseconds(80));
Check(fix == null && sw.Elapsed < TimeSpan.FromSeconds(2),"noncooperative network cannot hang");
Console.WriteLine($"{checks} location regression checks passed");
class Fake(Func<string,CancellationToken,Task<HttpResponseMessage>> send) : HttpMessageHandler { protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request,CancellationToken ct)=>send(request.RequestUri!.ToString(),ct); }
